const assert = require('node:assert/strict');
global.window = {};
require('../content.js');
const content = window.ESTONA_CONTENT;
const worlds = content.worlds;
const lessons = worlds.flatMap(world => world.lessons || []);
const examples = lessons.flatMap(lesson => lesson.examples || []).filter(x => x.status === 'validat');
const unique = new Map(examples.map(x => [x.time, x]));

assert.equal(unique.size, 147, 'El banc ha de contenir 147 exemples horaris únics validats');
assert.equal(content.bank.quarterExpressions.length, 48, 'Hi ha d’haver 48 combinacions de quarts');
assert.equal(content.bank.quarterExpressions.filter(x => x.validAlternatives?.length).length, 36, 'Hi ha d’haver 36 alternatives del sistema de rellotge');
assert.equal(unique.get('01:00').expression, 'la una');
assert.equal(unique.get('01:15').expression, 'un quart de dues');
assert.equal(unique.get('12:15').expression, "un quart d'una");
assert.equal(unique.get('08:30').expression, 'dos quarts de nou');
assert.equal(unique.get('08:05').expression, 'les vuit i cinc minuts');
assert.equal(unique.get('08:20').expression, 'un quart i cinc de nou');
assert.equal(unique.get('08:25').expression, 'un quart i deu de nou');
assert.equal(unique.get('08:35').expression, 'dos quarts i cinc de nou');
assert.equal(unique.get('08:40').expression, 'dos quarts i deu de nou');
assert.equal(unique.get('08:50').expression, 'tres quarts i cinc de nou');
assert.equal(unique.get('08:55').expression, 'tres quarts i deu de nou');
assert.equal(unique.get('12:20').expression, "un quart i cinc d'una");
assert.equal(unique.get('12:55').expression, "tres quarts i deu d'una");
assert.equal(unique.get('11:45').expression, 'tres quarts de dotze');
assert.equal(unique.get('12:46').expression, "tres quarts i un minut d’una");
assert.equal(unique.get('13:05').expression, 'la una i cinc minuts');
assert.equal(worlds.length, 8, 'ESTONA ha de mantenir els vuit mons');
assert.equal(lessons.filter(x => x.status === 'validat').length, 28, 'Hi ha d’haver 28 lliçons validades');
assert.equal(content.bank.halfQuarters.length, 2, 'Els dos exemples de mitjos quarts han de ser presents');
assert.ok(content.bank.halfQuarters.every(x => x.exactMinute === null), 'Els mitjos quarts no s’han de convertir en minuts exactes');
assert.ok(content.bank.approximateExpressions.every(x => x.exactMinute === null), 'Les expressions aproximatives no s’han de convertir en minuts exactes');
assert.equal(content.linguisticPolicy.correctionClasses.length, 4, 'Cal distingir les quatre categories de correcció');
console.log('ESTONA: banc lingüístic revisat correcte — 147 exemples únics, 48 quarts, 36 alternatives, vuit mons i 28 lliçons.');
